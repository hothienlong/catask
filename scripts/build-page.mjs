#!/usr/bin/env node
// Builds the shipped catask page from its readable source.
//
//   page-src/so-viec.src.html  (edit this)  ->  skills/daily-digest-todo/assets/so-viec.html  (shipped, generated)
//
// What it does:
//   - minifies every inline <style> (esbuild, loader css) and <script> (esbuild, loader js, target es2019);
//     UTF-8 is kept as is (--charset=utf8), so Vietnamese text stays readable and cheap in tokens;
//   - strips HTML comments and collapses indentation / blank lines in the markup (no change inside
//     <pre>/<textarea>; the static markup has none, those are built by the script at runtime);
//   - keeps every line short (esbuild --line-limit, markup wrapped at existing whitespace), so the
//     skill can Read the page in chunks before publishing it;
//   - checks the result: same ids / data-* attributes / <title>, every script passes `node --check`.
//
// Usage: node scripts/build-page.mjs [--check]   (--check: build to memory and fail if the shipped file differs)
// Needs Node 22 and network access the first time (npx downloads the pinned esbuild).

import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'page-src', 'so-viec.src.html');
const OUT = join(ROOT, 'skills', 'daily-digest-todo', 'assets', 'so-viec.html');
const ESBUILD = 'esbuild@0.24.0';
const LINE_LIMIT = 400;

function esbuild(code, loader) {
  const args = ['-y', ESBUILD, `--loader=${loader}`, '--minify', '--charset=utf8', `--line-limit=${LINE_LIMIT}`, '--log-level=warning'];
  if (loader === 'js') args.push('--target=es2019');
  return execFileSync('npx', args, { input: code, encoding: 'utf8', maxBuffer: 64 << 20 }).trim();
}

function minifyMarkup(html) {
  let s = html.replace(/<!--(?!\[if)[\s\S]*?-->/g, '');
  s = s.replace(/[ \t]*\n\s*/g, '\n').replace(/[ \t]{2,}/g, ' ');
  return s.split('\n').map(wrap).join('\n');
}

// Break an over-long markup line at a space that is already there, between attributes or in text
// (never inside a quoted attribute value, where a newline would change the value).
function wrap(line) {
  if (line.length <= LINE_LIMIT) return line;
  const out = [];
  let start = 0, last = -1, inTag = false, quote = '';
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (quote) { if (c === quote) quote = ''; continue; }
    else if (inTag && (c === '"' || c === "'")) quote = c;
    else if (c === '<') inTag = true;
    else if (c === '>') inTag = false;
    if (c === ' ' && !quote) last = i;
    if (i - start >= LINE_LIMIT && last > start) { out.push(line.slice(start, last)); start = last + 1; last = -1; }
  }
  out.push(line.slice(start));
  return out.join('\n');
}

function attrs(html, re) { return [...html.matchAll(re)].map((m) => m[0]).sort(); }

function build() {
  const src = readFileSync(SRC, 'utf8');
  const re = /<(style|script)(\s[^>]*)?>([\s\S]*?)<\/\1>/g;
  let out = '', last = 0, m;
  const scripts = [];
  while ((m = re.exec(src))) {
    if (m[2] && m[2].trim()) throw new Error(`<${m[1]}${m[2]}>: attributes on inline ${m[1]} are not supported by this build`);
    out += minifyMarkup(src.slice(last, m.index));
    const body = esbuild(m[3], m[1] === 'style' ? 'css' : 'js');
    if (/<\/(script|style)/i.test(body)) throw new Error(`minified ${m[1]} contains a closing tag`);
    if (m[1] === 'script') scripts.push(body);
    out += `<${m[1]}>\n${body}\n</${m[1]}>`;
    last = re.lastIndex;
  }
  out += minifyMarkup(src.slice(last));
  out = '<!-- Generated by scripts/build-page.mjs from page-src/so-viec.src.html. Do not edit; edit the source and rebuild. -->\n' + out.trim() + '\n';

  // Sanity checks: the markup the page and the skill rely on must survive unchanged.
  const markup = (h) => h.replace(re, '');
  for (const [name, rx] of [['ids', /(?<=\s)id="[^"]*"/g], ['data-* attributes', /(?<=\s)data-[\w-]+(="[^"]*")?/g], ['title', /<title>[^<]*<\/title>/g]]) {
    const a = attrs(markup(src), rx), b = attrs(markup(out), rx);
    if (a.join('\n') !== b.join('\n')) throw new Error(`build changed the page's ${name}`);
  }
  const srcScripts = [...src.matchAll(/<script>/g)].length;
  if (scripts.length !== srcScripts) throw new Error('script count changed');
  const dir = mkdtempSync(join(tmpdir(), 'catask-build-'));
  try {
    scripts.forEach((code, i) => { const f = join(dir, `s${i}.js`); writeFileSync(f, code); execFileSync(process.execPath, ['--check', f]); });
  } finally { rmSync(dir, { recursive: true, force: true }); }
  const longest = Math.max(...out.split('\n').map((l) => l.length));
  return { src, out, longest, lines: out.split('\n').length };
}

const { src, out, longest, lines } = build();
const kb = (s) => (Buffer.byteLength(s) / 1024).toFixed(1) + ' KB';
if (process.argv.includes('--check')) {
  const cur = readFileSync(OUT, 'utf8');
  if (cur !== out) { console.error('so-viec.html is stale: run node scripts/build-page.mjs'); process.exit(1); }
  console.log('so-viec.html is up to date');
} else {
  writeFileSync(OUT, out);
  console.log(`built ${OUT.slice(ROOT.length + 1)}: ${kb(src)} -> ${kb(out)}, ${lines} lines, longest ${longest} chars`);
}
